// Build browser metadata from the same reviewed catalogue used by Task sources.
// Never copy source document bodies, school annotations or browser state here.
import {readFile,writeFile} from 'node:fs/promises';
const base=new URL('../',import.meta.url);
const audit=JSON.parse(await readFile(new URL('task-sources/data.json',base),'utf8'));
const pick=(value,keys)=>Object.fromEntries(keys.filter(key=>value[key]!==undefined).map(key=>[key,value[key]]));
const referenceFields=['id','title','url','locator','relationship','verification','statusNote','linkKind','linkTitle','accessNote','verifiedOn'];
const sources=Object.fromEntries(audit.sources.map(source=>[source.id,pick(source,referenceFields)]));
const rows=Object.fromEntries(audit.rows.map(row=>[`${row.wing}:${row.id}`,{...pick(row,['id','wing','title','provenanceStatus','sourceBasis','sourceGap','sourceQuote','quoteSourceId','quoteLocator','quoteVerifiedOn']),evidenceRefs:(row.evidenceRefs||[]).map(ref=>pick(ref,referenceFields))}]));
const output={checkedAt:audit.checkedAt,linkAuditDate:audit.linkAuditDate||audit.checkedAt,rows,sources};
const json=JSON.stringify(output);
if (/"(?:localPath|localCopy|b64_string|file_uri|repositoryLocator)"|\b[A-Z]:[\\/]|AppData[\\/]/i.test(json)) throw Error('Private metadata in source links');
for(const source of [...Object.values(sources),...Object.values(rows).flatMap(row=>row.evidenceRefs)]) {
  if(!source.url)continue;
  const url=new URL(source.url);
  if(url.protocol!=='https:' || url.username || url.password)throw Error(`Unsafe source URL: ${source.id}`);
}
await writeFile(new URL('assets/js/data/task-source-links.js',base),`// Generated by scripts/build-task-source-links.mjs. Edit task-sources/data.json.\nwindow.WWHS_TASK_SOURCE_DATA = ${json};\n`);
console.log(`Built source links for ${Object.keys(rows).length} audited tasks and ${Object.keys(sources).length} sources.`);
